-- DATA-001: relational catalogue, ownership, wallets, materials and condition.
-- Character blobs remain in place during the compatibility/backfill period.

-- Live Supabase already had these prototype catalogues. Define them here as
-- well so a brand-new or restored database can run the full migration chain.
CREATE TABLE IF NOT EXISTS weapons (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
  value NUMERIC NOT NULL DEFAULT 0 CHECK (value >= 0),
  weight NUMERIC NOT NULL DEFAULT 0 CHECK (weight >= 0),
  default_quantity INTEGER NOT NULL DEFAULT 1 CHECK (default_quantity >= 0),
  stat TEXT NOT NULL DEFAULT 'str' CHECK (stat IN ('str','dex','con','int','bld_str','cha')),
  advantage TEXT NOT NULL DEFAULT 'Normal', to_hit_bonus INTEGER NOT NULL DEFAULT 0,
  damage_1 TEXT NOT NULL DEFAULT '1d4', damage_type_1 TEXT NOT NULL DEFAULT 'Other',
  damage_2 TEXT, damage_type_2 TEXT, proficient BOOLEAN NOT NULL DEFAULT TRUE,
  pools TEXT[] NOT NULL DEFAULT '{}', created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS armour (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
  value NUMERIC NOT NULL DEFAULT 0 CHECK (value >= 0),
  weight NUMERIC NOT NULL DEFAULT 0 CHECK (weight >= 0),
  default_quantity INTEGER NOT NULL DEFAULT 1 CHECK (default_quantity >= 0),
  base_ac INTEGER NOT NULL DEFAULT 10,
  armour_type TEXT NOT NULL DEFAULT 'Light' CHECK (armour_type IN ('Light','Medium','Heavy','Shield','Unarmoured')),
  max_dex_bonus INTEGER NOT NULL DEFAULT 0, proficient BOOLEAN NOT NULL DEFAULT TRUE,
  pools TEXT[] NOT NULL DEFAULT '{}', created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS items (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, item_type TEXT NOT NULL DEFAULT 'item',
  description TEXT NOT NULL DEFAULT '', value NUMERIC NOT NULL DEFAULT 0 CHECK (value >= 0),
  weight NUMERIC NOT NULL DEFAULT 0 CHECK (weight >= 0),
  default_quantity INTEGER NOT NULL DEFAULT 1 CHECK (default_quantity >= 0),
  effect TEXT, effect_amount TEXT, pools TEXT[] NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS item_materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  cost_modifier DOUBLE PRECISION NOT NULL DEFAULT 0,
  weight_modifier DOUBLE PRECISION NOT NULL DEFAULT 0,
  attack_bonus REAL NOT NULL DEFAULT 0,
  damage_modifier REAL NOT NULL DEFAULT 0,
  light_armour_modifier REAL NOT NULL DEFAULT 0,
  medium_armour_modifier REAL NOT NULL DEFAULT 0,
  heavy_armour_modifier REAL NOT NULL DEFAULT 0,
  medium_armour_stealth TEXT,
  heavy_armour_stealth TEXT,
  heavy_armour_strength_req REAL,
  is_iron BOOLEAN NOT NULL DEFAULT FALSE,
  drop_rate DOUBLE PRECISION,
  pool_restrict TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

DO $migration$
BEGIN
  IF to_regclass('public."Materials"') IS NOT NULL THEN
    EXECUTE $copy$
      INSERT INTO item_materials (
        id, name, cost_modifier, weight_modifier, attack_bonus, damage_modifier,
        light_armour_modifier, medium_armour_modifier, heavy_armour_modifier,
        medium_armour_stealth, heavy_armour_stealth, heavy_armour_strength_req,
        is_iron, drop_rate, pool_restrict, created_at
      )
      SELECT id, COALESCE(NULLIF(trim("Name"), ''), 'Material ' || id),
        COALESCE(cost_modifier, 0), COALESCE(weight_modifier, 0),
        COALESCE(attack_bonus, 0), COALESCE(damage_modifier, 0),
        COALESCE(light_armour_modifier, 0), COALESCE(medium_armour_modifier, 0),
        COALESCE(heavy_armour_modifier, 0), medium_armour_stealth,
        heavy_armour_stealth, heavy_armour_strength_req, COALESCE(is_iron, FALSE),
        drop_rate, pool_restrict, created_at FROM "Materials"
      ON CONFLICT (id) DO NOTHING
    $copy$;
  END IF;
END $migration$;

SELECT setval(
  pg_get_serial_sequence('item_materials', 'id'),
  GREATEST(COALESCE((SELECT max(id) FROM item_materials), 0), 1),
  EXISTS (SELECT 1 FROM item_materials)
);

