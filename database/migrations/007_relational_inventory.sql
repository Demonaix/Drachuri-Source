-- A rule belongs either to a named NPC pool or to an additive characteristic.
-- Three nullable definition columns retain real foreign keys without a weak
-- polymorphic item reference.
CREATE TABLE IF NOT EXISTS inventory_pool_rules (
  id BIGSERIAL PRIMARY KEY,
  owner_type TEXT NOT NULL CHECK (owner_type IN ('pool', 'characteristic')),
  owner_key TEXT NOT NULL,
  weapon_id TEXT REFERENCES weapons(id) ON UPDATE CASCADE ON DELETE CASCADE,
  armour_id TEXT REFERENCES armour(id) ON UPDATE CASCADE ON DELETE CASCADE,
  item_id TEXT REFERENCES items(id) ON UPDATE CASCADE ON DELETE CASCADE,
  chance NUMERIC NOT NULL DEFAULT 100 CHECK (chance >= 0 AND chance <= 100),
  alternative_group TEXT,
  group_required BOOLEAN NOT NULL DEFAULT FALSE,
  min_quantity INTEGER NOT NULL DEFAULT 1 CHECK (min_quantity >= 0),
  max_quantity INTEGER NOT NULL DEFAULT 1 CHECK (max_quantity >= min_quantity),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT inventory_pool_rule_one_definition CHECK (
    (weapon_id IS NOT NULL)::INTEGER +
    (armour_id IS NOT NULL)::INTEGER +
    (item_id IS NOT NULL)::INTEGER = 1
  ),
  UNIQUE NULLS NOT DISTINCT (
    owner_type, owner_key, weapon_id, armour_id, item_id, alternative_group
  )
);

CREATE INDEX IF NOT EXISTS inventory_pool_rules_owner_idx
  ON inventory_pool_rules(owner_type, lower(owner_key));
